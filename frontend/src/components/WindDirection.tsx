// Show a small rotating arrow with the compass direction for wind.
export function WindDirection({ degrees }: { degrees: number | null }) {
  const directions = [
    "N",
    "NNE",
    "NE",
    "ENE",
    "E",
    "ESE",
    "SE",
    "SSE",
    "S",
    "SSW",
    "SW",
    "WSW",
    "W",
    "WNW",
    "NW",
    "NNW",
  ];

  const hasValue = degrees !== null && Number.isFinite(degrees);
  const direction = hasValue
    ? directions[Math.round((((degrees % 360) + 360) % 360) / 22.5) % 16]
    : "—";

  return (
    <span
      className="wind-direction"
      title={hasValue ? `${direction} (${Math.round(degrees)}°)` : "No data"}
    >
      <svg
        width="14"
        height="14"
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        style={{ transform: hasValue ? `rotate(${degrees}deg)` : "none" }}
      >
        <line x1="12" y1="2" x2="12" y2="8" />
        <line x1="12" y1="16" x2="12" y2="22" />
        <line x1="4.93" y1="4.93" x2="7.76" y2="7.76" />
        <line x1="16.24" y1="16.24" x2="19.07" y2="19.07" />
        <line x1="2" y1="12" x2="8" y2="12" />
        <line x1="16" y1="12" x2="22" y2="12" />
        <line x1="4.93" y1="19.07" x2="7.76" y2="16.24" />
        <line x1="16.24" y1="7.76" x2="19.07" y2="4.93" />
      </svg>
      <span className="wind-direction-label">{direction}</span>
    </span>
  );
}
